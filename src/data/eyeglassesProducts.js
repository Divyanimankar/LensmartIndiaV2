/* =========================================
   SLUG BANANE WALA PART
   "Furla 729 Spectacle" -> "furla-729-spectacle-eyeglasses"
   "IDEE 2504"           -> "idee-2504-eyeglasses"
   (agar name mein brand pehle se hai to dobara nahi lagta)
========================================= */

const slugify = (text) =>
  String(text || "")
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

const makeSlug = (item) => {
  const name = String(item.name || "");
  const brand = String(item.brand || "");

  const nameHasBrand = name.toLowerCase().startsWith(brand.toLowerCase());
  const base = nameHasBrand ? name : `${brand} ${name}`;

  return slugify(`${base} eyeglasses`);
};

const usedSlugs = new Set();

export const eyeglassesProducts = rawEyeglassesProducts.map((item) => {
  let slug = item.slug || makeSlug(item);

  /* agar kabhi do products ka slug same ho jaye to id jod do */
  if (usedSlugs.has(slug)) slug = `${slug}-${item.id}`;
  usedSlugs.add(slug);

  return { ...item, slug };
});